"use client"

import { useEffect, useRef } from "react"
import { CircleAlert, FlaskConical, Sparkles } from "lucide-react"

import { Button } from "@/components/ui/button"
import type { Source } from "@/lib/session"
import { cn } from "@/lib/utils"

/** Screen heading that takes focus when the screen appears, for keyboard and screen-reader users. */
export function ScreenHeading({
  children,
  className,
}: {
  children: React.ReactNode
  className?: string
}) {
  const ref = useRef<HTMLHeadingElement>(null)
  useEffect(() => {
    ref.current?.focus({ preventScroll: true })
    window.scrollTo?.({ top: 0 })
  }, [])
  return (
    <h1
      ref={ref}
      tabIndex={-1}
      className={cn(
        "text-[2rem] leading-[1.15] outline-none sm:text-[2.5rem]",
        className
      )}
    >
      {children}
    </h1>
  )
}

export function Card({
  className,
  children,
}: {
  className?: string
  children: React.ReactNode
}) {
  return (
    <div
      className={cn(
        "rounded-2xl border border-border bg-card p-5 shadow-[0_1px_2px_oklch(0.3_0.02_85/0.05)] sm:p-6",
        className
      )}
    >
      {children}
    </div>
  )
}

export function SourceBadge({
  source,
  className,
}: {
  source: Source | null
  className?: string
}) {
  if (!source) return null
  const live = source === "live"
  const Icon = live ? Sparkles : FlaskConical
  return (
    <span
      className={cn(
        "inline-flex items-center gap-1.5 rounded-full px-2.5 py-1 text-xs font-medium",
        live ? "bg-sage-soft text-sage" : "bg-indigo-soft text-indigo",
        className
      )}
    >
      <Icon className="size-3.5" aria-hidden />
      {live
        ? "Generated by live AI"
        : "Demo Mode: prewritten, not AI-generated"}
    </span>
  )
}

export function ErrorNotice({
  message,
  onRetry,
  onUseDemo,
  extra,
}: {
  message: string
  onRetry?: () => void
  onUseDemo?: () => void
  extra?: React.ReactNode
}) {
  return (
    <div
      role="alert"
      className="rounded-xl border border-destructive/30 bg-card p-4 text-sm"
    >
      <p className="flex gap-2 text-foreground">
        <CircleAlert
          className="mt-0.5 size-4 shrink-0 text-destructive"
          aria-hidden
        />
        {message}
      </p>
      {(onRetry || onUseDemo || extra) && (
        <div className="mt-3 flex flex-wrap gap-2 pl-6">
          {onRetry && (
            <Button type="button" variant="outline" size="lg" onClick={onRetry}>
              Try again
            </Button>
          )}
          {onUseDemo && (
            <Button type="button" variant="ghost" size="lg" onClick={onUseDemo}>
              Continue in Demo Mode
            </Button>
          )}
          {extra}
        </div>
      )}
    </div>
  )
}

export function LoadingNotice({ children }: { children: React.ReactNode }) {
  return (
    <p
      role="status"
      className="flex items-center gap-2.5 text-sm text-muted-foreground"
    >
      <span
        aria-hidden
        className="size-2 animate-pulse rounded-full bg-primary"
      />
      {children}
    </p>
  )
}
